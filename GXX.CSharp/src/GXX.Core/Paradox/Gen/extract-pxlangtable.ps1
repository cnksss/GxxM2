[void]$out.AppendLine('    {')
[void]$out.AppendLine('        null, // index 0: Delphi lower bound is 1, this slot is never accessed')
for ($n = 0; $n -lt $entries.Count; $n++) {
  $e = $entries[$n]
  $idx = $n + 1
  $line = '        new TPxLang(Name: ' + $q + (CsStr $e.Name) + $q + ', SortOrder: ' + $e.SO + ', CodePage: ' + $e.CP + ', SortOrderID: ' + $q + (CsStr $e.SID) + $q + '), // [' + $idx + '] ParadoxDataSet.pas:' + $e.Line
  [void]$out.AppendLine($line)
}
[void]$out.AppendLine('    };')
[void]$out.AppendLine('}')
[void]$out.AppendLine('')

[System.IO.File]::WriteAllText($dst, $out.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "written $dst ($($entries.Count) entries)"
